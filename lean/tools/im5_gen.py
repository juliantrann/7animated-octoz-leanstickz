#!/usr/bin/env python3
"""Writes the largebin verification conditions of `_int_malloc` (PLAN.md G3, `malloc`): `FV7z/Im5/L<i>.lean`, one
theorem `vc_L<k>` per value of `k` (`nb = 16 k`), each `P5 k` (`FV7z/Im5/S0.lean`) by one `lwp` per piece between the
cut points 0, 512, 1115, 2012, 2549, and `vc_F<i>` (the file's range of `k`); `FV7z/Im5/P5.lean` (`pall`: every
`64 ≤ k ≤ 257`). Run from `lean/`: `python3 -I tools/im5_gen.py`."""

# One theorem per size: 9 s and 2 GB each (probe `im5_k*`, run a102). Eight in one proof (`ksplit`): out of memory
# at 14 GB.
PER_FILE = 16
KS = list(range(64, 258))
FILES = [KS[i:i + PER_FILE] for i in range(0, len(KS), PER_FILE)]

EXTRA = ("p1, p2, p3, p4, p5, p6, p7, q1, q2, q3, q5, q6, q7, q8, sk, qk, hS, hS', m, d1, d2, e, hgm, hfc, htb, htc,\n"
         "      hun, hm2, hm3")

PIECES = [
    ("0 → 512", "W_0, W_9, W_304, W_320, W_340, W_352, W_482, o0, o1, o2, o3, o4, o5, o6"),
    ("512 → 1115", "W_512, W_1069, W_1099, o7, o8, o9"),
    ("1115 → 2012", "W_1115, W_1138, W_1968, W_1977, o10, o11, o12, o13"),
    ("2012 → 2549", "W_2012, W_2048, W_2480, W_2488, W_2505, o14, o15, o16, o17, o18"),
]


def body(lo: int, hi: int) -> str:
    out = []
    for i, (name, blocks) in enumerate(PIECES):
        lead = "    " if i == 0 else "    any_goals "
        out.append(f"    -- {name}\n{lead}lwp [{blocks},\n      {EXTRA}]\n    lcl")
    return "\n".join(out)


def header(lo: int, hi: int) -> str:
    return f"""import FV7z.Im5.S0
/-!
# `_int_malloc` from the entry to 2549, `nb = 16 k`, `{lo} ≤ k ≤ {hi}` (PLAN.md G3, `malloc`)

`P5 k` (`Im5/S0.lean`): one theorem `vc_L<k>` per `k`, one `lwp` per piece; `vc_F{lo}` for the range. Generated by
`tools/im5_gen.py`. One theorem at a time (`Elab.async false`): `lean` on the command line elaborates them in
parallel, 2 GB each, past `-M5000` (a104: kernel excessive memory).
-/
set_option Elab.async false
open ZellicX86 Decode FV7z FV7z.Leaf FV7z.Fn FV7z.Start
open FV7z.Imm (imm imm_at rd_off rd_off_self rd_below stk_f pu)
namespace FV7z.Im5
variable {{F : Footprint}} {{Wl : List Rgn}}
"""


def thm(lo: int) -> str:
    return f"""
set_option maxHeartbeats 400000000 in
set_option maxRecDepth 100000 in
theorem vc_L{lo} (k : Nat) (hk1 : {lo} ≤ k) (hk2 : k ≤ {lo}) : P5 F Wl k := by
  intro fb S n g f V hrsp hsi hdi m d1 d2 e hS hlo hfb hgm hfc sk htc htb hun hm2 hm3 hW hgf htf hsw hsd
  obtain ⟨rax, rcx, rdx, rbx, rsp, rbp, rsi, rdi, r8, r9, r10, r11, r12, r13, r14, r15⟩ := g
  dsimp only at hrsp hsi hdi ⊢
  subst hrsp hsi hdi
  obtain ⟨p1, p2, p3, p4, p5, p6, p7⟩ := pu S
  have qk := rd_below (S := S) (x := BitVec.ofNat 64 (7940768 + 16 * lbi k)) (n := 8)
    (hx := by rw [BitVec.toNat_ofNat]; have := lbi_le k; omega) (hS := hS)
  have q1 := rd_below (S := S) (x := 8013224#64) (n := 8) (hx := by rw [BitVec.toNat_ofNat]; omega) (hS := hS)
  have q2 := rd_below (S := S) (x := 7940680#64) (n := 4) (hx := by rw [BitVec.toNat_ofNat]; omega) (hS := hS)
  have q3 := rd_below (S := S) (n := 8) (hx := hfb) (hS := hS)
  have q5 := rd_below (S := S) (x := 7940592#64) (n := 8) (hx := by rw [BitVec.toNat_ofNat]; omega) (hS := hS)
  have q6 := rd_below (S := S) (x := 7940792#64) (n := 8) (hx := by rw [BitVec.toNat_ofNat]; omega) (hS := hS)
  have q7 := rd_below (S := S) (x := 7942824#64) (n := 4) (hx := by rw [BitVec.toNat_ofNat]; omega) (hS := hS)
  have q8 := rd_below (S := S) (x := 7942828#64) (n := 4) (hx := by rw [BitVec.toNat_ofNat]; omega) (hS := hS)
  have hS' : S.toNat + 256 < 18446744073709551616 := hS
  have D : ∀ (x : Addr) (n : Nat), 7940480 ≤ x.toNat → x.toNat + n ≤ 7943136 →
      ∀ i < n, Foot F.data (Addr.add x i) :=
    fun x n h1 h2 i hi => hW _ (by simp only [Addr.add]; bv_omega) (by simp only [Addr.add]; bv_omega)
  obtain rfl : k = {lo} := by omega
  ( simp only [lbi, Nat.reduceMul, Nat.reduceDiv, Nat.reduceAdd, Nat.reduceLeDiff, ite_true, ite_false, reduceIte]
      at e sk qk ⊢
{body(lo, lo)})
"""


def chain(ks: list, name: str, sub: str, lo: int, hi: int) -> str:
    """`by_cases` over the ranges `ks` (pairs `(a, b)`), each closed by `sub` at `a`."""
    cases = []
    karg = "(k := k)" if sub == "vc_F" else "k"  # `vc_F*` (the chains) take `k` implicitly, `vc_L*` explicitly
    for a, b in ks[:-1]:
        cases.append(f"  by_cases h{b} : k ≤ {b}\n  · exact {sub}{a} {karg} (by omega) h{b}")
    a, b = ks[-1]
    cases.append(f"  exact {sub}{a} {karg} (by omega) h2")
    return (f"theorem {name} {{k : Nat}} (h1 : {lo} ≤ k) (h2 : k ≤ {hi}) : P5 F Wl k := by\n"
            + "\n".join(cases) + "\n")


def p5() -> str:
    imps = "".join(f"import FV7z.Im5.L{i}\n" for i in range(1, len(FILES) + 1))
    rng = [(ks[0], ks[-1]) for ks in FILES]
    return imps + f"""/-!
# `P5 k` for every largebin size `64 ≤ k ≤ 257` (PLAN.md G3, `malloc`)

`pall`: the theorems `vc_F*` of `Im5/L1.lean` … `L{len(FILES)}.lean`. Generated by `tools/im5_gen.py`.
-/
open ZellicX86 Decode FV7z FV7z.Leaf FV7z.Fn FV7z.Start
namespace FV7z.Im5
variable {{F : Footprint}} {{Wl : List Rgn}}

""" + chain(rng, "pall", "vc_F", 64, 257) + """
end FV7z.Im5
"""


def main() -> None:
    outs = {}
    for i, ks in enumerate(FILES, 1):
        lo, hi = ks[0], ks[-1]
        outs[f"FV7z/Im5/L{i}.lean"] = (header(lo, hi) + "".join(thm(k) for k in ks) + "\n"
                                       + chain([(k, k) for k in ks], f"vc_F{lo}", "vc_L", lo, hi)
                                       + "\nend FV7z.Im5\n")
    outs["FV7z/Im5/P5.lean"] = p5()
    for name, text in outs.items():
        for n, line in enumerate(text.splitlines(), 1):
            assert len(line) <= 120, (name, n, len(line))
        with open(name, "w", encoding="utf-8") as fh:
            fh.write(text)


if __name__ == "__main__":
    main()
