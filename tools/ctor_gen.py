#!/usr/bin/env python3
"""Generate lean/FV7z/Ctor/Code.lean, Lea*.lean and Chains.lean: the constructors of `.init_array` (PLAN.md §M).

  Code.lean  the bytes of 7zzs 26.06 from the first constructor to `_start` (`0x41c140` to `0x41d350`), where all 101
             lie, as one list `sti`, pinned to the file by `decide +kernel`.
  Lea*.lean  for each constructor `endbr64; lea rdi, [rip + d]; jmp R` with R one of the three registrars (64 of
             them): its 16 bytes as a pattern, what they decode to, where they lie in `sti`, the stretch to the `jmp`
             as a `BlkA` (`rdi` set to the argument), the `jmp`'s `Dec`; and `leas`, the table of the 64 (`csuTg`
             number, offset in `sti`, registrar, argument).
  Chains.lean for each constructor `endbr64; sub rsp, 8; (lea rdi, [rip + d]; call R)+; lea rdi, [rip + d];
             add rsp, 8; jmp R` (8 of them): its bytes, decodings, prologue, stretches, `call`s and `jmp` as
             `CallsAt`; and `chains`, the table (`csuTg` number, offset, calls).

The decodings are checked by Lean (`rfl`), not taken from here: a wrong one fails the build.
Usage (from the main repo or a worktree): python3 -I tools/ctor_gen.py [release/26.06/7zzs] [lean]
"""
import os
import struct
import sys
import textwrap

STI, END = 0x41C140, 0x41D350  # the first constructor; `_start`
PART = 16  # constructors a file
REG = {0x5CEB20: (0, "RegisterArc"), 0x458E60: (1, "RegisterCodec"), 0x458E90: (2, "RegisterHasher")}


def loader(path):
    d = open(path, "rb").read()
    phoff, = struct.unpack_from("<Q", d, 0x20)
    pe, pn = struct.unpack_from("<HH", d, 0x36)
    segs = []
    for i in range(pn):
        t, _, off, va, _, fsz = struct.unpack_from("<IIQQQQ", d, phoff + i * pe)
        if t == 1:
            segs.append((va, off, fsz))

    def rd(a, n):
        for va, off, fsz in segs:
            if va <= a and a + n <= va + fsz:
                return d[off + a - va:off + a - va + n]
        raise ValueError(hex(a))
    return rd


def blist(bs, ind="  "):
    xs = [f"0x{b:02x}" for b in bs]
    return ",\n".join(ind + ", ".join(xs[i:i + 16]) for i in range(0, len(xs), 16))


def main():
    elf = sys.argv[1] if len(sys.argv) > 1 else "release/26.06/7zzs"
    out = sys.argv[2] if len(sys.argv) > 2 else "lean"
    rd = loader(elf)
    arr = [struct.unpack_from("<Q", rd(0x7777A0, 0x330), i)[0] for i in range(0, 0x330, 8)]
    sti = rd(STI, END - STI)
    leas = []
    for m in range(3, 104):  # `csuTg m` is the entry m - 2 of `.init_array`
        a = arr[m - 2]
        assert STI <= a < END, hex(a)
        b = rd(a, 16)
        if b[:4] != bytes.fromhex("f30f1efa") or b[4:7] != bytes.fromhex("488d3d") or b[11] != 0xE9:
            continue
        d, = struct.unpack_from("<i", b, 7)
        r, = struct.unpack_from("<i", b, 12)
        tgt = (a + 16 + r) % 2**64
        if tgt not in REG:
            continue
        leas.append(dict(m=m, a=a, j=a - STI, b=b, d=d % 2**64, r=r % 2**64, A=(a + 11 + d) % 2**64, tgt=tgt))
    chains = []
    for m in range(3, 104):
        a = arr[m - 2]
        b = rd(a, 4 + 4 + 12 * 8 + 16)
        if b[:8] != bytes.fromhex("f30f1efa4883ec08"):
            continue
        p, cs = 8, []
        while b[p:p + 3] == bytes.fromhex("488d3d") and b[p + 7] == 0xE8:
            d, = struct.unpack_from("<i", b, p + 3)
            r, = struct.unpack_from("<i", b, p + 8)
            cs.append(dict(p=p, d=d % 2**64, r=r % 2**64, A=(a + p + 7 + d) % 2**64, tgt=(a + p + 12 + r) % 2**64,
                           last=False))
            p += 12
        if b[p:p + 3] != bytes.fromhex("488d3d") or b[p + 7:p + 11] != bytes.fromhex("4883c408") or b[p + 11] != 0xE9:
            continue
        d, = struct.unpack_from("<i", b, p + 3)
        r, = struct.unpack_from("<i", b, p + 12)
        cs.append(dict(p=p, d=d % 2**64, r=r % 2**64, A=(a + p + 7 + d) % 2**64, tgt=(a + p + 16 + r) % 2**64,
                       last=True))
        if not cs[:-1] or any(c["tgt"] not in REG for c in cs):
            continue
        chains.append(dict(m=m, a=a, j=a - STI, b=b[:p + 16], cs=cs))
    os.makedirs(f"{out}/FV7z/Ctor", exist_ok=True)
    with open(f"{out}/FV7z/Ctor/Code.lean", "w") as f:
        f.write(f"""import ZellicX86.Spec.Executable
import FV7z.Image
import FV7z.Lemmas.InsFn
/-!
# The code of the constructors of `.init_array` in `7zzs` (PLAN.md §M, constructors)

The bytes from the first constructor to `_start` (`0x{STI:x}` to `0x{END:x}`), where the 101 constructors of
`.init_array` lie, as a list, and the fact that they are the file's (`sti_pin`, by the kernel's evaluation of Zellic's
ELF reader). Generated by `tools/ctor_gen.py`.
-/
namespace FV7z.Ctor
set_option maxRecDepth 100000
open ZellicX86

/-- `0x{STI:x}` to `0x{END:x}` of `7zzs`. -/
def sti : List Byte := [
{blist(sti)}]

theorem sti_pin : Exe.bytesAt V2606.zzs.blob 0x{STI:x} {len(sti)} = some sti := by decide +kernel
theorem sti_length : sti.length = {len(sti)} := by decide +kernel

/-- Where the code lies in `7zzs`. -/
abbrev sti_at : Addr := 0x{STI:x}

theorem sti_lt {{j : Nat}} (h : j < {len(sti)}) : j < sti.length := sti_length ▸ h

end FV7z.Ctor
""")
    body = []
    for c in leas:
        j, nm = c["j"], f"q{c['j']}"
        body.append(f"""/-- `csuTg {c['m']}`, at `0x{c['a']:x}`: `{REG[c['tgt']][1]} (0x{c['A']:x})`. -/
def {nm} : List Byte := [
{blist(c['b'])}]
theorem {nm}_0 : ∀ feat, Dec feat {nm} 0 (FV7z.mk .endbr64 32 [] 4) :=
  by intro feat f; rfl
theorem {nm}_4 : ∀ feat, Dec feat {nm} 4 (FV7z.mk .lea 64 [gr 64 7, .mem (mrip {c['d']} 0)] 7) :=
  by intro feat f; rfl
theorem {nm}_11 : ∀ feat, Dec feat {nm} 11 (FV7z.mk .jmp 64 [.rel {c['r']}] 5) :=
  by intro feat f; rfl
theorem w{j} : {nm} <+: sti.drop {j} := by decide +kernel
theorem bq{j} (prof : Profile) : BlkA prof {nm} (0x{c['a']:x} : Addr) 0 11 [Op.nop, Op.mov 64 7 (.i {c['A']})] :=
  .cons ({nm}_0 _) ((OpI.endbr).at _) (by decide) <|
  .cons ({nm}_4 _) (OpIA.lea_rip (by decide)) (by decide) <|
  .nil 11
theorem b{j} (prof : Profile) : BlkA prof sti sti_at {j} {j + 11} [Op.nop, Op.mov 64 7 (.i {c['A']})] :=
  (bq{j} prof).shift (by decide) w{j}
theorem j{j} (feat : Features) : Dec feat sti {j + 11} (FV7z.mk .jmp 64 [.rel {c['r']}] 5) :=
  Dec.shift (j := {j}) (k := 11) ({nm}_11 feat) w{j} (by decide)
""")
    rows = ",\n".join(f"  ({c['m']}, {c['j']}, {REG[c['tgt']][0]}, {c['A']})" for c in leas)
    parts = [body[i:i + PART] for i in range(0, len(body), PART)]
    for k, part in enumerate(parts, 1):
        with open(f"{out}/FV7z/Ctor/Lea{k}.lean", "w") as f:
            f.write(f"""import FV7z.Ctor.Code
import FV7z.Lemmas.Sp
import FV7z.Lemmas.BlkOps2
/-!
# The constructors that only call a registrar, part {k} of {len(parts)} (PLAN.md §M, constructors)

Generated by `tools/ctor_gen.py`; see `Lea.lean`.
-/
namespace FV7z.Ctor
set_option maxRecDepth 100000
open ZellicX86 Decode FV7z.Leaf

{chr(10).join(part)}
end FV7z.Ctor
""")
    alts = ["⟨rfl, rfl, rfl, rfl⟩"] * len(leas)
    pats = " |\n      ".join(" | ".join(alts[i:i + 3]) for i in range(0, len(alts), 3))
    cases = "\n".join(f"  · exact ⟨{c['r']}, ⟨b{c['j']} prof, j{c['j']} _⟩, by decide⟩" for c in leas)
    imports = "\n".join(f"import FV7z.Ctor.Lea{k}" for k in range(1, len(parts) + 1))
    with open(f"{out}/FV7z/Ctor/Lea.lean", "w") as f:
        f.write(f"""{imports}
/-!
# The constructors that only call a registrar (PLAN.md §M, constructors)

{len(leas)} of the constructors of `.init_array` are `endbr64; lea rdi, [rip + d]; jmp R`, `R` one of 7-Zip's three
registrars (`RegisterArc` `0x5ceb20`, `RegisterCodec` `0x458e60`, `RegisterHasher` `0x458e90`): `R (&info)`, a tail
call. For each, at offset `j` of `sti` (in `Lea1.lean` to `Lea{len(parts)}.lean`: the kernel's memory for the
evaluations adds up within a file): its bytes `q<j>`, what they decode to, where they lie (`w<j>`), the stretch to
the `jmp` (`b<j>`: `rdi` set to the argument) and the `jmp` (`j<j>`). `leas`: the table of them. Generated by
`tools/ctor_gen.py`.
-/
namespace FV7z.Ctor
open ZellicX86 Decode FV7z.Leaf

/-- The constructors that only call a registrar: their number `m` in `csuTg`, offset in `sti`, registrar (0
`RegisterArc`, 1 `RegisterCodec`, 2 `RegisterHasher`) and argument. -/
def leas : List (Nat × Nat × Nat × Nat) := [
{rows}]

/-- The registrars by their number in `leas`. -/
def regAt : Nat → Addr
  | 0 => 0x5ceb20
  | 1 => 0x458e60
  | _ => 0x458e90

/-- The stretch to the `jmp` of the constructor at offset `j` (`rdi` set to `A`), and the `jmp` (`rel`). -/
def LeaAt (prof : Profile) (j A rel : Nat) : Prop :=
  BlkA prof sti sti_at j (j + 11) [Op.nop, Op.mov 64 7 (.i A)] ∧
    Dec prof.feat sti (j + 11) (FV7z.mk .jmp 64 [.rel rel] 5)

/-- Each constructor of `leas`: its stretch and `jmp`, which goes to its registrar. -/
theorem lea_at (prof : Profile) {{m j r A : Nat}} (h : (m, j, r, A) ∈ leas) :
    ∃ rel, LeaAt prof j A rel ∧ sti_at.add (j + 11 + 5) + BitVec.ofNat 64 rel = (regAt r).add 0 := by
  simp only [leas, List.mem_cons, Prod.mk.injEq, List.not_mem_nil, or_false] at h
  rcases h with {pats}
{cases}

end FV7z.Ctor
""")
    write_chains(out, chains)
    print(f"sti: {len(sti)} bytes; {len(leas)} constructors lea+jmp; {len(chains)} chains")


def write_chains(out, chains):
    """`Chains.lean`: for each constructor `endbr64; sub rsp, 8; (lea rdi, [rip + d]; call R)+; lea rdi, [rip + d];
    add rsp, 8; jmp R`: its bytes, decodings, stretches and `CallsAt`; the table `chains`."""
    body = []
    for ch in chains:
        j, a, nm = ch["j"], ch["a"], f"c{ch['j']}"
        names = ", ".join(f"`{REG[c['tgt']][1]} (0x{c['A']:x})`" for c in ch["cs"])
        doc = textwrap.fill(f"/-- `csuTg {ch['m']}`, at `0x{a:x}`: {names}. -/", 120, break_on_hyphens=False)
        t = [f"""{doc}
def {nm} : List Byte := [
{blist(ch['b'])}]
theorem {nm}_0 : ∀ feat, Dec feat {nm} 0 (FV7z.mk .endbr64 32 [] 4) := by dec_rfl
theorem {nm}_4 : ∀ feat, Dec feat {nm} 4 (FV7z.mk .sub 64 [gr 64 4, Src.opd 64 (.i 8)] 4) := by dec_rfl"""]
        for c in ch["cs"]:
            p = c["p"]
            t.append(f"theorem {nm}_{p} : ∀ feat, Dec feat {nm} {p} (FV7z.mk .lea 64 [gr 64 7, .mem (mrip {c['d']} 0)] 7) :=\n"
                     "  by dec_rfl")
            if c["last"]:
                t.append(f"theorem {nm}_{p + 7} : ∀ feat, Dec feat {nm} {p + 7} "
                         "(FV7z.mk .add 64 [gr 64 4, Src.opd 64 (.i 8)] 4) := by dec_rfl")
                t.append(f"theorem {nm}_{p + 11} : ∀ feat, Dec feat {nm} {p + 11} (FV7z.mk .jmp 64 [.rel {c['r']}] 5) :=\n"
                         "  by dec_rfl")
            else:
                t.append(f"theorem {nm}_{p + 7} : ∀ feat, Dec feat {nm} {p + 7} (FV7z.mk .call 64 [.rel {c['r']}] 5) :=\n"
                         "  by dec_rfl")
        t.append(f"""theorem v{j} : {nm} <+: sti.drop {j} := by decide +kernel
theorem pq{j} (prof : Profile) : BlkA prof {nm} (0x{a:x} : Addr) 0 8 [Op.nop, Op.sub 64 4 (.i 8)] :=
  .cons ({nm}_0 _) ((OpI.endbr).at _) (by decide) <|
  .cons ({nm}_4 _) ((OpI.sub (.i 8) (.inr rfl)).at _) (by decide) <|
  .nil 8
theorem pb{j} (prof : Profile) : BlkA prof sti sti_at {j} {j + 8} [Op.nop, Op.sub 64 4 (.i 8)] :=
  (pq{j} prof).shift (by decide) v{j}""")
        for c in ch["cs"]:
            p, A = c["p"], c["A"]
            if c["last"]:
                ops, k = f"[Op.mov 64 7 (.i {A}), Op.add 64 4 (.i 8)]", 11
                add = f"\n  .cons ({nm}_{p + 7} _) ((OpI.add (.i 8) (.inr rfl)).at _) (by decide) <|"
                ins = f"(FV7z.mk .jmp 64 [.rel {c['r']}] 5)"
            else:
                ops, k, add = f"[Op.mov 64 7 (.i {A})]", 7, ""
                ins = f"(FV7z.mk .call 64 [.rel {c['r']}] 5)"
            t.append(f"""theorem lq{j}_{p} (prof : Profile) :
    BlkA prof {nm} (0x{a:x} : Addr) {p} {p + k} {ops} :=
  .cons ({nm}_{p} _) (OpIA.lea_rip (by decide)) (by decide) <|{add}
  .nil {p + k}
theorem lb{j}_{p} (prof : Profile) :
    BlkA prof sti sti_at {j + p} {j + p + k} {ops} :=
  (lq{j}_{p} prof).shift (by decide) v{j}
theorem ld{j}_{p} (feat : Features) : Dec feat sti {j + p + k} {ins} :=
  Dec.shift (j := {j}) (k := {p + k}) ({nm}_{p + k} feat) v{j} (by decide)""")
        its = [f"({REG[c['tgt']][0]}, {c['A']})" for c in ch["cs"]]
        lst = ",\n    ".join(", ".join(its[i:i + 4]) for i in range(0, len(its), 4))
        steps = " <|\n  ".join(
            f"CallsAt.{'last' if c['last'] else 'mid'} (lb{j}_{c['p']} prof) (ld{j}_{c['p']} _)\n    (sti_lt (by decide)) (by decide)"
            for c in ch["cs"])
        t.append(f"""theorem cs{j} (prof : Profile) : CallsAt prof {j + 8} [{lst}] :=
  {steps}
""")
        body.append("\n".join(t))
        ch["lst"] = lst
    rows = ",\n".join(f"  ({ch['m']}, {ch['j']}, [{ch['lst']}])" for ch in chains)
    pats = " | ".join(["rfl"] * len(chains))
    cases = "\n".join(f"  · exact ⟨by decide +kernel, pb{ch['j']} prof, cs{ch['j']} prof⟩" for ch in chains)
    with open(f"{out}/FV7z/Ctor/Chains.lean", "w") as f:
        f.write(f"""import FV7z.Ctor.ChainGo
/-!
# The constructors that call registrars one after the other: the code (PLAN.md §M, constructors)

{len(chains)} of the constructors of `.init_array` are `endbr64; sub rsp, 8`, then `lea rdi, [rip + d]; call R` one or
more times, then `lea rdi, [rip + d]; add rsp, 8; jmp R`, each `R` one of the three registrars. For each, at offset
`j` of `sti`: its bytes `c<j>`, what they decode to, where they lie (`v<j>`), the prologue (`pb<j>`), each `lea` with
its `call` or `add` and `jmp` (`lb<j>_<p>`, `ld<j>_<p>`), and the calls as `CallsAt` (`cs<j>`). `chains`: the table
of them. Generated by `tools/ctor_gen.py`.
-/
namespace FV7z.Ctor
set_option maxRecDepth 100000
open ZellicX86 Decode FV7z FV7z.Leaf FV7z.Start

{chr(10).join(body)}
/-- The constructors that call registrars one after the other: their number `m` in `csuTg`, offset in `sti`, and
the calls (registrar, argument). -/
def chains : List (Nat × Nat × List (Nat × Nat)) := [
{rows}]

/-- Each constructor of `chains`: the entry of `.init_array` its number says, its prologue and its calls. -/
theorem chain_at (prof : Profile) : ∀ x ∈ chains, csuTg x.1 = sti_at.add x.2.1 ∧
    BlkA prof sti sti_at x.2.1 (x.2.1 + 8) [Op.nop, Op.sub 64 4 (.i 8)] ∧ CallsAt prof (x.2.1 + 8) x.2.2 := by
  intro x hx
  simp only [chains, List.mem_cons, List.not_mem_nil, or_false] at hx
  rcases hx with {pats}
{cases}

end FV7z.Ctor
""")


if __name__ == "__main__":
    main()
