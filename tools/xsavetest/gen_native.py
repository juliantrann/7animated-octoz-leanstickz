#!/usr/bin/env python3
"""Writes tools/xsavetest/native.c, the processor's side of the XSAVE/XSAVEC/XRSTOR differential test: one function
per instruction and register width, each a single asm statement that sets the state, runs the instruction and stores
the state, so that no compiled code runs in between. Usage: gen_native.py (in any directory)."""
import os

LEG, Z, K, LEGO, ZO, KO = 0, 512, 2560, 2624, 3136, 5184   # offsets in struct st
OPS = ["xsave", "xsave64", "xsavec", "xsavec64", "xrstor", "xrstor64"]

def body(op, wide):
    s = [f"fxrstor64 {LEG}(%%rsi)"]
    if wide:
        s += [f"vmovdqu64 {Z + 64 * j}(%%rsi), %%zmm{j}" for j in range(32)]
        s += [f"kmovq {K + 8 * j}(%%rsi), %%k{j}" for j in range(8)]
    else:
        s += [f"vmovdqu {Z + 64 * j}(%%rsi), %%ymm{j}" for j in range(16)]
    s += [f"{op} (%%rdi)", f"fxsave64 {LEGO}(%%rsi)"]
    if wide:
        s += [f"vmovdqu64 %%zmm{j}, {ZO + 64 * j}(%%rsi)" for j in range(32)]
        s += [f"kmovq %%k{j}, {KO + 8 * j}(%%rsi)" for j in range(8)]
    else:
        s += [f"vmovdqu %%ymm{j}, {ZO + 64 * j}(%%rsi)" for j in range(16)]
    s += ["fninit", "vzeroupper"]
    return "\\n\\t".join(s)

def main():
    clob = ", ".join(f'"xmm{j}"' for j in range(16))
    fns = []
    for op in OPS:
        for wide in (0, 1):
            fns.append(f'''static void run_{op}_{wide}(struct st *t, uint8_t *area, uint32_t lo, uint32_t hi) {{
  __asm__ volatile("{body(op, wide)}" :: "S"(t), "D"(area), "a"(lo), "d"(hi) : "memory", "st", {clob});
}}''')
    table = ",\n  ".join(f'{{"{op}", {{run_{op}_0, run_{op}_1}}}}' for op in OPS)
    src = TEMPLATE.format(Z=Z, K=K, LEGO=LEGO, ZO=ZO, KO=KO, fns="\n".join(fns), table=table)
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "native.c"), "w").write(src)

TEMPLATE = r'''// The processor's side of the differential test of XSAVE, XSAVEC and XRSTOR (PLAN.md §6.4, G1); lean/Tools/XsaveTest.lean
// is the model's side and documents the case format. Generated by tools/xsavetest/gen_native.py: do not edit.
// Each case: the page (the area at OFF in it, the next page unmapped) and the state are set (FXRSTOR64 of LEGACY, then
// YMM0-YMM15, or with AVX-512 ZMM0-ZMM31 and k0-k7), the instruction runs on [rdi] with EDX:EAX, and the page and the
// state (FXSAVE64, the vector and opmask registers) are printed. SIGSEGV is reported as `gp` (si_code SI_KERNEL) or
// `pf`, SIGILL as `ud`. `native info` prints the processor's profile for the model (`xsavetest`'s arguments).
#define _GNU_SOURCE
#include <cpuid.h>
#include <setjmp.h>
#include <signal.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/mman.h>

struct st {{ uint8_t leg[512], z[32][64], k[8][8], lego[512], zo[32][64], ko[8][8]; }} __attribute__((aligned(64)));
_Static_assert(__builtin_offsetof(struct st, z) == {Z} && __builtin_offsetof(struct st, k) == {K} &&
               __builtin_offsetof(struct st, lego) == {LEGO} && __builtin_offsetof(struct st, zo) == {ZO} &&
               __builtin_offsetof(struct st, ko) == {KO}, "offsets");

{fns}

static const struct {{ const char *name; void (*f[2])(struct st *, uint8_t *, uint32_t, uint32_t); }} OPS[] = {{
  {table}
}};

static sigjmp_buf jb;
static volatile int sig, scode;
static void handler(int s, siginfo_t *si, void *uc) {{ (void)uc; sig = s; scode = si->si_code; siglongjmp(jb, 1); }}
static int hex(int c) {{ return c <= '9' ? c - '0' : (c | 32) - 'a' + 10; }}
static void parse(const char *s, uint8_t *out, size_t n) {{ for (size_t i = 0; i < n; i++) out[i] = hex(s[2*i]) << 4 | hex(s[2*i+1]); }}
static void put(const uint8_t *b, size_t n) {{ for (size_t i = 0; i < n; i++) printf("%02x", b[i]); }}
static uint64_t xgetbv0(void) {{ uint32_t a, d; __asm__ volatile("xgetbv" : "=a"(a), "=d"(d) : "c"(0)); return (uint64_t)d << 32 | a; }}

int main(int argc, char **argv) {{
  unsigned a = 0, b = 0, c = 0, d = 0;
  uint64_t xcr0 = xgetbv0();
  int wide = (xcr0 & 0xE0) == 0xE0 && __get_cpuid_count(7, 0, &a, &b, &c, &d) && (b >> 30 & 1);   // AVX-512 with BW
  if (argc > 1 && !strcmp(argv[1], "info")) {{
    static struct st t; __asm__ volatile("fxsave64 %0" : "=m"(t.leg));
    uint32_t mask; memcpy(&mask, t.leg + 28, 4);
    __get_cpuid(0, &a, &b, &c, &d); int amd = b == 0x68747541;
    __get_cpuid_count(7, 0, &a, &b, &c, &d); int fdpexc = b >> 6 & 1, fcsdep = b >> 13 & 1;
    int amderr = __get_cpuid(0x80000008, &a, &b, &c, &d) && (b >> 2 & 1);
    printf("xcr0=%llx mxcsrmask=%x amd=%d amderr=%d fcsdep=%d fdpexc=%d wide=%d", (unsigned long long)xcr0, mask, amd,
           amderr, fcsdep, fdpexc, wide);
    for (int i = 0; i < 20; i++) {{ __cpuid_count(0xD, i, a, b, c, d); printf(" d%d=%x,%x,%x", i, a, b, c); }}
    putchar('\n'); return 0;
  }}
  uint8_t *region = mmap(0, 2 * 4096, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
  mprotect(region + 4096, 4096, PROT_NONE);
  struct sigaction sa = {{0}}; sa.sa_sigaction = handler; sa.sa_flags = SA_SIGINFO | SA_NODEFER;
  sigaction(SIGSEGV, &sa, 0); sigaction(SIGILL, &sa, 0); sigaction(SIGBUS, &sa, 0);
  static char line[1 << 16];
  static struct st t;
  while (fgets(line, sizeof line, stdin)) {{
    char *f[12]; int n = 0;
    for (char *s = strtok(line, " \n"); s && n < 12; s = strtok(0, " \n")) f[n++] = s;
    if (n != 10) {{ puts("bad"); continue; }}
    int k = -1;
    for (int i = 0; i < 6; i++) if (!strcmp(f[0], OPS[i].name)) k = i;
    if (k < 0) {{ puts("bad"); continue; }}
    uint64_t rax = strtoull(f[1], 0, 16), rdx = strtoull(f[2], 0, 16), off = strtoull(f[3], 0, 16);
    memset(&t, 0, sizeof t);
    parse(f[4], t.leg, 512);
    uint8_t ymmh[16][16], zmmh[16][32], zhi[16][64];
    parse(f[5], &ymmh[0][0], sizeof ymmh); parse(f[6], &zmmh[0][0], sizeof zmmh); parse(f[7], &zhi[0][0], sizeof zhi);
    parse(f[8], &t.k[0][0], sizeof t.k);
    for (int j = 0; j < 16; j++) {{
      memcpy(t.z[j], t.leg + 160 + 16 * j, 16); memcpy(t.z[j] + 16, ymmh[j], 16); memcpy(t.z[j] + 32, zmmh[j], 32);
      memcpy(t.z[16 + j], zhi[j], 64);
    }}
    parse(f[9], region, 4096);
    sig = 0;
    if (sigsetjmp(jb, 1) == 0) OPS[k].f[wide](&t, region + off, (uint32_t)rax, (uint32_t)rdx);
    if (sig == SIGSEGV) {{ printf("exc %s\n", scode == SI_KERNEL ? "gp" : "pf"); continue; }}
    if (sig == SIGILL) {{ puts("exc ud"); continue; }}
    if (sig == SIGBUS) {{ puts("exc ac"); continue; }}
    printf("ok "); put(region, 4096); putchar(' '); put(t.lego, 512); putchar(' ');
    put(&t.zo[0][0], sizeof t.zo); putchar(' '); put(&t.ko[0][0], sizeof t.ko); putchar('\n');
  }}
  return 0;
}}
'''

if __name__ == "__main__":
    main()
